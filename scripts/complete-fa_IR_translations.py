def apply_translations(po_path: Path) -> tuple[int, int]:
    po = polib.pofile(str(po_path))
    applied = 0
    missing = 0

    for entry in po:
        if not entry.msgid:
            continue
        if entry.msgstr and entry.msgstr.strip() and entry.msgstr != entry.msgid:
            continue
        if entry.msgid in TRANSLATIONS:
            entry.msgstr = TRANSLATIONS[entry.msgid]
            applied += 1
        else:
            missing += 1

    po.save(str(po_path))
    mo_path = po_path.with_suffix(".mo")
    po.save_as_mofile(str(mo_path))
    return applied, missing


def main() -> None:
    po_files = list(ROOT.glob("platform-*/languages/*-fa_IR.po"))
    total_applied = 0
    total_missing = 0

    for po_path in sorted(po_files):
        applied, missing = apply_translations(po_path)
        total_applied += applied
        total_missing += missing
        print(f"{po_path.relative_to(ROOT)}: applied={applied}, still_missing={missing}")

    print(f"TOTAL applied={total_applied}, still_missing={total_missing}")


if __name__ == "__main__":
    main()
